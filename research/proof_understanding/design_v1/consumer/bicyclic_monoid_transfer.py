"""Source-inspired assumption transfer from group algebra to a bicyclic monoid.

The transformation monoid M is generated by L(n)=max(n-1,0) and R(n)=n+1
under function composition; p=L,q=R satisfy pq=1 but qp != 1.

This gives an elementary *MONOID algebra* one-sided inverse and a local-rule
operator on K^M that is injective but not surjective. It does NOT provide a
group-algebra example or independently verify the Kaplansky source result.
"""
from __future__ import annotations
from dataclasses import dataclass
from typing import Callable
import argparse,json

def left(n:int)->int:
    if type(n) is not int or n<0:raise ValueError("n must be natural")
    return max(n-1,0)

def right(n:int)->int:
    if type(n) is not int or n<0:raise ValueError("n must be natural")
    return n+1

def compose(f:Callable[[int],int],g:Callable[[int],int],n:int)->int:
    return f(g(n))

def verify_prefix(N:int=100)->dict:
    if N<1:raise ValueError("need nonempty prefix")
    pq_all=all(compose(left,right,n)==n for n in range(N))
    witness=compose(right,left,0)
    return {
      "checked_n":N,
      "p_times_q_identity_on_prefix":pq_all,
      "q_times_p_not_identity_witness_at_0":witness!=0,
      "qp_at_0":witness,
      "pq_at_0":compose(left,right,0),
    }

def mathematical_certificate()->dict:
    # The following two identities have symbolic proofs valid for every n:
    # L(R(n))=max((n+1)-1,0)=n, for n in Nat.
    # R(L(0))=R(0)=1 !=0; hence R o L != identity function.
    # Then in monoid algebra K[M], the singleton basis elements
    # a=[L],b=[R] multiply to 1=[Id] but b*a=[R o L] !=1.
    #
    # T_b y(g)=y(g*R). Since Id*R=R and (R o L)*R=R o (L o R)=R,
    # every image vector z satisfies z(Id)=z(R o L).
    # Delta_Id violates this, so T_b is not surjective.
    return {
      "structure":"transformation monoid of natural-number functions generated by L,R",
      "multiplication":"composition f*g = f after g",
      "a":"basis element of L","b":"basis element of R",
      "pq_equals_identity":"L(R(n))=n for every n>=0",
      "qp_differs":"R(L(0))=1 !=0, hence R o L != identity",
      "algebra_implication":"In K[M], [L]*[R]=[Id] but [R]*[L] != [Id].",
      "operator_definition":"T_c(x)(g)=sum_m c_m*x(g*m) on all K^M",
      "operator_injectivity":"T_[L] composed with T_[R]=T_[Id]=identity",
      "image_constraint":"For y=T_[R] x, y(Id)=x(R)=y(R o L).",
      "excluded_configuration":"delta_Id(Id)=1, delta_Id(R o L)=0, so delta_Id is not in image",
      "source_scope":"does not assert existence of any such a,b in a GROUP algebra",
      "advanced_source_theorem_verified":False,
      "mathematical_status":"short independent elementary symbolic proof"
    }

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--prefix",type=int,default=100)
    args=p.parse_args()
    prefix=verify_prefix(args.prefix)
    assert prefix["p_times_q_identity_on_prefix"]
    assert prefix["q_times_p_not_identity_witness_at_0"]
    print(json.dumps({"check":prefix,"certificate":mathematical_certificate()},indent=2))

if __name__=="__main__":main()
